_KK_LETTERS = re.compile("[әғқңөұүһіӘҒҚҢӨҰҮҺІ]")


def _norm(city: str) -> str:
    low = (city or "").lower().replace("ё", "е").strip()
    return re.sub(r"^(г\.|город|қ\.)\s*", "", low)


def region_of(city: str) -> str:
    """Регион по городу или пустая строка, если город неизвестен или не наш."""
    norm = _norm(city)
    if not norm:
        return ""
    for region, keys in _REGION_KEYS.items():
        if any(k in norm for k in keys):
            return region
    return ""


def live_signals(texts: list[str], voice_count: int) -> dict:
    """То, что видно по самим сообщениям, без модели: длина, голос, казахские буквы.

    Работает уже на первом сообщении, когда портрета ещё нет.
    """
    texts = [t for t in texts if (t or "").strip()]
    total = len(texts) + voice_count
    avg = sum(len(t) for t in texts) / len(texts) if texts else 0
    return {
        "avg_len": round(avg),
        "voice_share": (voice_count / total) if total else 0.0,
        "kk_letters": any(_KK_LETTERS.search(t) for t in texts),
        "count": total,
    }


def _tone_lines(signals: dict) -> list[str]:
    lines = []
    if signals.get("count"):
        if signals["avg_len"] and signals["avg_len"] <= 45:
            lines.append(
                "Клиент пишет коротко — отвечай так же: 1–3 коротких предложения, "
                "не больше одного вопроса."
            )
        elif signals["avg_len"] >= 160:
            lines.append("Клиент пишет развёрнуто — можно отвечать подробнее, но без таблиц.")
        if signals["voice_share"] >= 0.5:
            lines.append(
                "Клиенту удобнее голосом — пиши так, как сказал бы вслух, и предложи "
                "звонок менеджера, если вопрос непростой."
            )
    return lines


def _language_line(profile: dict, signals: dict) -> str:
    lang = profile.get("language") or ("kk" if signals.get("kk_letters") else "")
    level = profile.get("russian_level") or ""
    if lang == "kk":
        return (
            "Язык: казахский. Весь ответ — на казахском, включая подписи к ссылкам и "
            "файлам; не переходи на русский сам. Если клиент пишет по-казахски русскими "
            "буквами или латиницей — отвечай на нормальном казахском, простыми словами; "
            "сложный термин можно продублировать по-русски в скобках."
        )
    if lang == "mixed" or level in ("с ошибками", "слабо"):
        return (
            "Русский для клиента не родной: короткие простые фразы, одна мысль в "
            "абзаце, без идиом и сложных терминов. Если клиент вставляет казахские "
            "слова — можно отвечать на казахском."
        )
    return ""


def directives(profile: dict, signals: dict) -> list[str]:
    """Указания «как говорить с этим клиентом» — от самых важных к второстепенным."""
    lines: list[str] = []
    emotion = profile.get("emotion") or ""
    # «Заинтересован — не тяни» спорит с «взял паузу — не дави»; пауза важнее.
    if emotion == "интерес" and profile.get("stance") in _STANCE_STYLE:
        emotion = ""
    if _EMOTION_STYLE.get(emotion):
        lines.append(_EMOTION_STYLE[emotion])
    lang = _language_line(profile, signals)
    if lang:
        lines.append(lang)
    lines += _tone_lines(signals)
    if _MOTIVE_STYLE.get(profile.get("motive") or ""):
        lines.append(_MOTIVE_STYLE[profile["motive"]])

    if profile.get("choice_stress") == "высокий":
        lines.append(
            "Клиенту тяжело выбрать — сними с него этот груз: не больше двух вариантов, "
            "один из них твоя рекомендация с ОДНОЙ причиной из его же слов. Можно "
            "«Если бы выбирала для себя, взяла бы …, потому что …». Скажи, что перед "
            "счётом менеджер всё перепроверит."
        )
    if profile.get("budget") == "чувствителен к цене":
        lines.append(
            "Чувствителен к цене: начинай с самого доступного подходящего варианта из "
            "каталога, сумму называй на весь объём; дорогой вариант — только как "
            "альтернатива."
        )
    for key, table in (("stance", _STANCE_STYLE), ("role", _ROLE_STYLE)):
        if table.get(profile.get(key) or ""):
            lines.append(table[profile[key]])
    if _AGE_STYLE.get(profile.get("age_band") or ""):
        lines.append(_AGE_STYLE[profile["age_band"]])

    region = region_of(profile.get("city") or "")
    if region:
        lines.append(
            _REGION_STYLE[region]
            + " Это лишь подсказка: как человек пишет на самом деле, важнее."
        )
    return lines


# Поля портрета, которые показываем модели как «уже известно» — по-русски.
_FACT_LABELS = (
    ("name", "Имя"),
    ("city", "Город"),
    ("object", "Задача"),
    ("size", "Объём"),
    ("preferences", "Нравится"),
    ("rejected", "Не подошло"),
    ("deadline", "Сроки"),
    ("decision_makers", "Кто решает"),
)


def profile_block(profile: dict, signals: dict) -> str:
    """Блок для системного промпта. Пусто, если о клиенте ещё ничего не понятно."""
    facts = [f"{label}: {profile[key]}" for key, label in _FACT_LABELS if profile.get(key)]
    how = directives(profile, signals)
    need = (profile.get("main_need") or "").strip()
    blockers = (profile.get("blockers") or "").strip()
    objections = [o for o in profile.get("objections") or [] if o]
    questions = [q for q in profile.get("open_questions") or [] if q]
    if not (facts or how or need or blockers or objections or questions):
        return ""

    out = ["ПОРТРЕТ КЛИЕНТА — собран из переписки. Клиенту о нём не говори."]
    if facts:
        out.append("Уже известно (не переспрашивай): " + "; ".join(facts) + ".")
    if need:
        out.append(f"Главная потребность: {need}")
    if blockers:
        out.append(f"Что мешает решиться: {blockers}")
    if objections:
        out.append("Возражения, которые уже звучали: " + "; ".join(objections) + ".")
    if questions:
        out.append(
            "ВОПРОСЫ КЛИЕНТА БЕЗ ОТВЕТА — ответь на них в первую очередь; если ответа нет "
            "в каталоге и базе знаний, вызови ask_admin: " + "; ".join(questions) + "."
        )
    if how:
        out.append("КАК С НИМ ГОВОРИТЬ:\n" + "\n".join(f"• {line}" for line in how))
    return "\n".join(out)
