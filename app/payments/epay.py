"""Halyk Bank ePay (epay.homebank.kz).

The card form is a browser widget (epay.js), so ``create_payment`` returns a URL
to a small page we host (``/pay/epay/{code}``) that initializes the widget with a
fresh OAuth token; confirmation arrives via PostLink.
"""

from __future__ import annotations

import hashlib
import hmac
import json
import logging

import httpx

from app.config import get_settings
from app.db.models.enums import PaymentProviderType, PaymentStatus
from app.payments.base import (
    PaymentProvider,
    PaymentRequest,
    PaymentResult,
    VerifiedPayment,
    to_amount,
)

logger = logging.getLogger(__name__)

_PAID_STATUSES = {"AUTH", "CHARGE", "PAID", "OK"}


def invoice_id_for(order_id: int) -> str:
    """ePay requires ``invoiceID`` to be 6–15 numeric digits, unique per order (and
    unique on its last 6 digits) — our human-friendly ``Order.code`` is alphanumeric
    (e.g. "A3F9K2"), so derive a numeric id from the DB primary key instead, which is
    unique by construction and trivially satisfies both constraints."""
    return str(order_id).zfill(6)


def _secret_hash(invoice_id: str) -> str:
    """Per-invoice value ePay echoes back verbatim in the PostLink callback.

    ePay's docs specify no fixed algorithm for ``secret_hash`` — just "a secret value
    generated by the merchant's system" (max 32 chars) — so we derive it deterministically
    from our own SECRET_KEY instead of storing a random value per order. That means:
    no extra DB column, and on callback we can recompute + compare it to prove the
    notification actually corresponds to a token WE requested. Without this, ePay's
    PostLink carries no signature at all.
    """
    key = get_settings().secret_key.encode()
    return hmac.new(key, f"epay:{invoice_id}".encode(), hashlib.sha256).hexdigest()[:32]


class EpayProvider(PaymentProvider):
    type = PaymentProviderType.EPAY

    @property
    def _oauth_host(self) -> str:
        return (
            "https://testoauth.homebank.kz"
            if self.config.get("test")
            else "https://epay-oauth.homebank.kz"
        )

    async def get_token(self, *, invoice_id: str, amount: int) -> dict:
        data = {
            "grant_type": "client_credentials",
            "scope": "webapi usermanagement email_send verification statement statistics payment",
            "client_id": self.config.get("client_id", ""),
            "client_secret": self.config.get("client_secret", ""),
            "invoiceID": invoice_id,
            "secret_hash": _secret_hash(invoice_id),
            "amount": amount,
            "currency": self.config.get("currency", "KZT"),
            "terminal": self.config.get("terminal", ""),
            "postLink": self.config.get("post_link", ""),
        }
        async with httpx.AsyncClient(timeout=httpx.Timeout(30.0, connect=10.0)) as client:
            resp = await client.post(f"{self._oauth_host}/oauth2/token", data=data)
            if resp.status_code >= 400:
                # The exact rejection reason (bad terminal/client_id/format) only shows
                # up in the body — surface it so a misconfigured merchant account is
                # diagnosable from the logs instead of a bare "не удалось начать оплату".
                logger.error("ePay token request failed %s: %s", resp.status_code, resp.text[:400])
            resp.raise_for_status()
            return resp.json()

    async def create_payment(self, req: PaymentRequest) -> PaymentResult:
        # Point the customer at our hosted widget page (it fetches a token on load).
        base_url = get_settings().base_url.rstrip("/")
        return PaymentResult(
            status=PaymentStatus.PENDING,
            checkout_url=f"{base_url}/pay/epay/{req.order_code}",
        )

    async def verify_webhook(self, *, headers: dict, body: bytes, form: dict) -> VerifiedPayment:
        try:
            payload = json.loads(body) if body else dict(form)
        except json.JSONDecodeError:
            payload = dict(form)

        invoice_id = str(payload.get("invoiceId") or payload.get("invoiceID") or "").strip()
        code = payload.get("code")
        status_val = str(payload.get("status") or "").upper()
        paid = code in {"ok", "0", 0} or status_val in _PAID_STATUSES

        # Real verification: recompute the secret_hash we sent at token-request time
        # and compare it to what ePay echoed back. This is the only signal ePay's
        # PostLink carries at all — without it, anyone who knows the URL could POST a
        # fake "paid" notification. ``trust_postlink`` remains as a manual escape
        # hatch (e.g. if a terminal config strips secret_hash from the callback) for
        # an admin who has separately IP-allowlisted the endpoint to Halyk.
        secret_ok = bool(invoice_id) and hmac.compare_digest(
            str(payload.get("secret_hash") or ""), _secret_hash(invoice_id)
        )

        return VerifiedPayment(
            status=PaymentStatus.CONFIRMED if paid else PaymentStatus.PENDING,
            order_code=invoice_id or None,
            external_id=payload.get("id") or payload.get("reference"),
            amount_kzt=to_amount(payload.get("amount")),
            signature_ok=secret_ok or bool(self.config.get("trust_postlink")),
            raw=payload,
        )
